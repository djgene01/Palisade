using System.Globalization;
using System.Text;

namespace Palisade.Core;

public sealed record GeneratedFiles(string Nftables, string Dnsmasq, string LanInterface, string Sysctl)
{
    /// <summary>Makes a wired internet port ask the provider for an address. Not used when that port is a Wi-Fi radio.</summary>
    public string WanInterface { get; init; } = "";
    /// <summary>Extra name servers for devices whose filter level differs from the network's. Empty when none do.</summary>
    public IReadOnlyList<DnsInstance> DnsInstances { get; init; } = [];
}

/// <summary>
/// Turns one validated config into the complete text of every system file.
/// Pure functions: the whole ruleset is rendered each time and swapped in atomically, live state is never patched.
/// </summary>
public static class ConfigRenderer
{
    public const string UsageTable = "palisade_usage";
    public const string UsageUpSet = "sent";
    public const string UsageDownSet = "received";

    // Forwarding makes the machine a router. The two ARP lines make each port answer only for its own
    // address: without them, two ports on the same network (a cabled internet port plus a Wi-Fi
    // maintenance port) answer for each other, and the other port then gives its address up as "taken".
    public const string Sysctl = "net.ipv4.ip_forward=1\nnet.ipv4.conf.all.arp_ignore=1\nnet.ipv4.conf.all.arp_announce=2\n";

    private const string Header = "# Generated by Palisade. Do not edit: changes are overwritten on the next save.";

    public static GeneratedFiles Render(FirewallConfig c) =>
        new(Nftables(c), Dnsmasq(c), LanInterface(c), Sysctl) { DnsInstances = DnsInstances(c), WanInterface = WifiPlan.WiredStanza(c.WanInterface) };

    public static string Nftables(FirewallConfig c)
    {
        var wan = Quote(c.WanInterface);
        var lan = Quote(c.LanInterface);
        var manage = $"{{ {string.Join(", ", PalisadeDefaults.ManagementPorts)} }}";
        var enforced = FilterPlan.Enforced(c);
        var instances = FilterPlan.InstanceLevels(c);
        const string dns = "meta l4proto { tcp, udp } th dport";
        var home = Ip4.TryParse(c.LanAddress, out var lanIp)
            ? $"{lanIp.Network(c.LanPrefix)}/{c.LanPrefix.ToString(CultureInfo.InvariantCulture)}"
            : throw new InvalidOperationException($"Unsafe address in config: {c.LanAddress}");
        var sb = new StringBuilder();
        void L(string line = "") => sb.Append(line).Append('\n');

        L("#!/usr/sbin/nft -f");
        L(Header);
        L();
        L("flush ruleset");
        L();
        L("table inet palisade {");
        // Filled by the agent from the clock: devices that are paused or inside one of their off times.
        L($"    set {AccessPlan.PausedSet} {{ type ether_addr; }}");
        if (c.Filter.BlockRelays)
            L($"    set {RelayPlan.SeenSet} {{ type ether_addr; size 1024; flags dynamic; counter; }}");
        // Filled by the name server as a limited device looks its allowed sites up.
        foreach (var limit in c.Limits)
            L($"    set {LimitPlan.SetName(limit.Mac)} {{ type ipv4_addr; size 65535; }}");
        L();
        L("    chain input {");
        L("        type filter hook input priority filter; policy drop;");
        L("        iif \"lo\" accept");
        L("        ct state established,related accept");
        L("        ct state invalid drop");
        L("        meta l4proto { icmp, ipv6-icmp } accept");
        L($"        iifname {lan} udp dport {{ 53, 67 }} accept");
        L($"        iifname {lan} tcp dport 53 accept");
        if (instances.Count > 0)
            L($"        iifname {lan} {dns} {{ {string.Join(", ", instances.Select(FilterPlan.Port))} }} accept comment \"filtered lookups\"");
        L($"        iifname {lan} tcp dport {manage} accept comment \"manage from home network\"");
        if (c.AllowManagementFromWan)
            L($"        iifname {wan} tcp dport {manage} accept comment \"manage from internet side\"");
        if (c.MaintenanceInterface.Length > 0)
            L($"        iifname {Quote(c.MaintenanceInterface)} tcp dport {manage} accept comment \"manage from maintenance port\"");
        L("    }");
        L();
        L("    chain forward {");
        L("        type filter hook forward priority filter; policy drop;");
        // Ahead of the "established" line on purpose: a pause must also stop a video that is already playing.
        L($"        iifname {lan} ether saddr @{AccessPlan.PausedSet} counter reject with icmpx type admin-prohibited comment \"paused or in an off time\"");
        if (c.Filter.BlockRelays)
            L($"        iifname {lan} ip daddr {RelayPlan.TrapAddress} update @{RelayPlan.SeenSet} {{ ether saddr }} reject with icmpx type admin-prohibited comment \"tried a connection-sharing service\"");
        // Ahead of the "established" line for the same reason as a pause: setting a limit must also cut
        // what the device already has open. The clock is let through, since nothing secure works with a wrong one.
        foreach (var limit in c.Limits)
        {
            L($"        iifname {lan} oifname {wan} ether saddr {Mac(limit.Mac)} udp dport 123 accept comment \"clock for a limited device\"");
            L($"        iifname {lan} oifname {wan} ether saddr {Mac(limit.Mac)} ip daddr != @{LimitPlan.SetName(limit.Mac)} counter reject with icmpx type admin-prohibited comment \"limited to chosen sites\"");
        }
        L("        ct state established,related accept");
        L("        ct state invalid drop");
        // Extra networks share the home port, so everything between them and the home network both arrives
        // and leaves on that port. Home devices may start a conversation; devices there may only answer.
        foreach (var n in c.ExtraNetworks)
        {
            L($"        iifname {lan} oifname {lan} ip saddr {home} ip daddr {n.Range()} accept comment {Quote("home network to " + n.Name)}");
            if (!n.InternetAccess)
                L($"        iifname {lan} oifname {wan} ip saddr {n.Range()} counter reject with icmpx type admin-prohibited comment {Quote(n.Name + " may not use the internet")}");
        }
        if (enforced)
        {
            // Port 853 carries encrypted lookups that would pass straight by the filter. Devices set to
            // "no filtering" keep it, since nothing is being enforced for them.
            var exempt = MacSet(c, FilterLevel.Off);
            L($"        iifname {lan} oifname {wan} {(exempt is null ? "" : $"ether saddr != {exempt} ")}{dns} 853 counter reject with icmpx type admin-prohibited comment \"encrypted lookups that skip the filter\"");
        }
        foreach (var rule in c.Rules.Where(r => r.Enabled))
            L("        " + RuleLine(rule, wan, lan));
        L($"        iifname {wan} oifname {lan} ct status dnat accept comment \"opened ports\"");
        L($"        iifname {lan} oifname {wan} accept comment \"home network to internet\"");
        L("    }");
        L();
        L("    chain output {");
        L("        type filter hook output priority filter; policy accept;");
        L("    }");
        L("}");
        L();
        L("table ip palisade_nat {");
        L("    chain prerouting {");
        L("        type nat hook prerouting priority dstnat; policy accept;");
        foreach (var f in c.PortForwards.Where(f => f.Enabled))
        {
            var range = PortSpec.TryParseRange(f.ExternalPort, out var parsed) ? parsed : default;
            var target = f.InternalPort is { } port && range.From == range.To
                ? $"{Address(f.InternalAddress)}:{port.ToString(CultureInfo.InvariantCulture)}"
                : Address(f.InternalAddress);
            foreach (var proto in f.Protocol == Protocol.TcpUdp ? new[] { "tcp", "udp" } : [f.Protocol == Protocol.Udp ? "udp" : "tcp"])
                L($"        iifname {wan} {proto} dport {range} dnat to {target} comment {Quote(f.Name)}");
        }
        if (enforced)
        {
            // Whatever name server a device asks, the question is answered here, by the server for that device's level.
            foreach (var level in instances)
                L($"        iifname {lan} ether saddr {MacSet(c, level)} {dns} 53 counter redirect to :{FilterPlan.Port(level)} comment \"lookups for the {FilterPlan.Name(level)} level\"");
            L($"        iifname {lan} {dns} 53 counter redirect to :53 comment \"all other lookups\"");
        }
        L("    }");
        L();
        L("    chain postrouting {");
        L("        type nat hook postrouting priority srcnat; policy accept;");
        if (c.NatEnabled)
            L($"        oifname {wan} masquerade");
        // A camera with a hand-set address often has no way back to another range. Arriving from the
        // firewall's own address in its range, it can always answer.
        foreach (var n in c.ExtraNetworks)
            L($"        oifname {lan} ip saddr {home} ip daddr {n.Range()} masquerade comment {Quote("reach " + n.Name)}");
        L("    }");
        L("}");
        L();
        // Counts bytes per home-network address for the overview. It runs ahead of the filter chain
        // (which accepts most packets on its first lines) and never decides anything itself.
        L($"table inet {UsageTable} {{");
        foreach (var set in new[] { UsageUpSet, UsageDownSet })
            L($"    set {set} {{ type ipv4_addr; size 4096; flags dynamic,timeout; counter; timeout 1d; }}");
        L("    chain count {");
        L("        type filter hook forward priority -10; policy accept;");
        L($"        iifname {lan} oifname {wan} ip saddr {home} update @{UsageUpSet} {{ ip saddr }}");
        L($"        iifname {wan} oifname {lan} ip daddr {home} update @{UsageDownSet} {{ ip daddr }}");
        L("    }");
        L("}");
        return sb.ToString();
    }

    private static string RuleLine(FirewallRule r, string wan, string lan)
    {
        var parts = new List<string>
        {
            r.Direction == RuleDirection.Outgoing ? $"iifname {lan} oifname {wan}" : $"iifname {wan} oifname {lan}",
        };
        if (r.Source.Length > 0) parts.Add($"ip saddr {Address(r.Source)}");
        if (r.Destination.Length > 0) parts.Add($"ip daddr {Address(r.Destination)}");

        var ports = PortSpec.TryParseList(r.Ports, out var list) ? $"{{ {string.Join(", ", list)} }}" : null;
        switch (r.Protocol)
        {
            case Protocol.Tcp: parts.Add(ports is null ? "meta l4proto tcp" : $"tcp dport {ports}"); break;
            case Protocol.Udp: parts.Add(ports is null ? "meta l4proto udp" : $"udp dport {ports}"); break;
            case Protocol.TcpUdp: parts.Add("meta l4proto { tcp, udp }" + (ports is null ? "" : $" th dport {ports}")); break;
            case Protocol.Icmp: parts.Add("meta l4proto icmp"); break;
        }

        parts.Add("counter");
        // Rejecting outgoing traffic tells the device straight away, so apps fail fast instead of hanging.
        parts.Add(r.Action == RuleAction.Allow ? "accept"
            : r.Direction == RuleDirection.Outgoing ? "reject with icmpx type admin-prohibited" : "drop");
        parts.Add($"comment {Quote(r.Name)}");
        return string.Join(' ', parts);
    }

    private static string? MacSet(FirewallConfig c, FilterLevel level)
    {
        var macs = FilterPlan.Overrides(c).Where(d => d.Level == level).Select(d => Mac(d.Mac)).ToList();
        return macs.Count == 0 ? null : $"{{ {string.Join(", ", macs)} }}";
    }

    /// <summary>The lines every name server shares: where to ask, and which sites to refuse or let through.</summary>
    private static void LookupLines(FirewallConfig c, FilterLevel level, Action<string> L)
    {
        L("domain-needed");
        L("bogus-priv");
        L("cache-size=1000");
        var servers = FilterPlan.Servers(level, c);
        if (servers.Count > 0)
        {
            // Only ever one kind of server per instance: dnsmasq uses whichever answers, so mixing a
            // filtering server with a plain one would let blocked sites through at random.
            L("no-resolv");
            foreach (var server in servers) L($"server={Address(server)}");
        }
        L($"local=/{FilterPlan.CheckName}/");
        foreach (var site in c.Filter.BlockedSites) L($"local=/{Site(site)}/");
        // Relay names get an answer, but one that leads to the trap: the firewall then sees which device came knocking.
        if (c.Filter.BlockRelays)
            foreach (var name in FilterPlan.RelayNames)
            {
                L($"address=/{Site(name)}/{RelayPlan.TrapAddress}");
                L($"address=/{Site(name)}/::");
            }
        // Each allowed site's addresses go onto the list of every device allowed to reach it.
        foreach (var site in c.Limits.SelectMany(LimitPlan.Sites).Distinct())
            L($"nftset=/{Site(site)}/{string.Join(',', c.Limits.Where(l => LimitPlan.Sites(l).Contains(site)).Select(l => $"4#inet#palisade#{LimitPlan.SetName(l.Mac)}"))}");
        if (level == FilterLevel.Off) return;
        foreach (var name in FilterPlan.BypassNames) L($"local=/{Site(name)}/");
        foreach (var site in c.Filter.AllowedSites)
            foreach (var server in FilterPlan.PlainServers(c))
                L($"server=/{Site(site)}/{Address(server)}");
    }

    public static IReadOnlyList<DnsInstance> DnsInstances(FirewallConfig c) =>
        [.. FilterPlan.InstanceLevels(c).Select(level =>
        {
            var sb = new StringBuilder();
            void L(string line) => sb.Append(line).Append('\n');
            L(Header);
            L($"port={FilterPlan.Port(level).ToString(CultureInfo.InvariantCulture)}");
            L($"interface={Token(c.LanInterface)}");
            L("bind-dynamic");
            L("no-hosts");
            LookupLines(c, level, L);
            return new DnsInstance(level, FilterPlan.Name(level), FilterPlan.Port(level), sb.ToString());
        })];

    public static string Dnsmasq(FirewallConfig c)
    {
        var d = c.Dhcp;
        var sb = new StringBuilder();
        void L(string line) => sb.Append(line).Append('\n');

        L(Header);
        L($"interface={Token(c.LanInterface)}");
        L("bind-dynamic");
        LookupLines(c, c.Filter.Level, L);
        if (d.Enabled)
        {
            L("dhcp-authoritative");
            L($"dhcp-range={Address(d.RangeStart)},{Address(d.RangeEnd)},{Ip4.MaskString(c.LanPrefix)},{d.LeaseHours.ToString(CultureInfo.InvariantCulture)}h");
            L($"dhcp-option=option:router,{Address(c.LanAddress)}");
            L($"dhcp-option=option:dns-server,{Address(c.LanAddress)}");
            foreach (var r in d.Reservations)
                L($"dhcp-host={Token(r.Mac)},{Address(r.Address)},{Token(r.Name)}");
        }
        return sb.ToString();
    }

    public static string LanInterface(FirewallConfig c) =>
        $"{Header}\nauto {Token(c.LanInterface)}\niface {Token(c.LanInterface)} inet static\n    address {LanAddresses(c)[0]}\n"
        + string.Concat(LanAddresses(c).Skip(1).Select(a => $"    up ip addr add {a} dev {Token(c.LanInterface)}\n"));

    /// <summary>Every address the home network port carries: the firewall's own first, then one per extra network.</summary>
    public static IReadOnlyList<string> LanAddresses(FirewallConfig c) =>
        [$"{Address(c.LanAddress)}/{c.LanPrefix.ToString(CultureInfo.InvariantCulture)}",
         .. c.ExtraNetworks.Select(n => $"{Address(n.Address)}/{(n.Prefix is >= 16 and <= 30 ? n.Prefix : throw new InvalidOperationException("Unsafe network size in config.")).ToString(CultureInfo.InvariantCulture)}")];

    // The validator already rejects unsafe input. These re-check at the point of output so a
    // config that skipped validation can never smuggle syntax into a root-owned file.
    private static string Address(string text) =>
        AddressSpec.TryNormalize(text, out var normalized) ? normalized : throw new InvalidOperationException($"Unsafe address in config: {text}");

    private static string Mac(string text) =>
        ConfigValidator.TryNormalizeMac(text, out var mac) && mac == text ? mac : throw new InvalidOperationException($"Unsafe hardware address in config: {text}");

    private static string Site(string text) =>
        SiteName.IsValid(text) ? text : throw new InvalidOperationException($"Unsafe site name in config: {text}");

    private static string Token(string text) =>
        text.Length > 0 && text.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is '_' or '.' or '-' or ':')
            ? text : throw new InvalidOperationException($"Unsafe value in config: {text}");

    private static string Quote(string text) =>
        text.Length > 0 && text.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is ' ' or '_' or '.' or ',' or '(' or ')' or '-')
            ? $"\"{text}\"" : throw new InvalidOperationException($"Unsafe text in config: {text}");
}

public static class LeaseParser
{
    /// <summary>Parses dnsmasq's lease file: "expiry mac address hostname client-id" per line.</summary>
    public static List<DhcpLease> Parse(string text)
    {
        var leases = new List<DhcpLease>();
        foreach (var line in text.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var p = line.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (p.Length < 4 || !long.TryParse(p[0], out var expiry) || !Ip4.TryParse(p[2], out _)) continue;
            leases.Add(new DhcpLease(DateTimeOffset.FromUnixTimeSeconds(expiry), p[1].ToLowerInvariant(), p[2], p[3] == "*" ? null : p[3]));
        }
        return leases;
    }
}
