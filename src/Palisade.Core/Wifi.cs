using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace Palisade.Core;

/// <summary>What the firewall's own Wi-Fi radio is doing. Interface is empty when the machine has no Wi-Fi.</summary>
public sealed class WifiStatus
{
    public string Interface { get; set; } = "";
    public string Ssid { get; set; } = "";
    public bool Connected { get; set; }
    public string Address { get; set; } = "";
}

/// <summary>The Wi-Fi network to join. The password is used once to derive a key and is never stored or sent back.</summary>
public sealed class WifiRequest
{
    public string Ssid { get; set; } = "";
    public string Passphrase { get; set; } = "";
}

public static class WifiPlan
{
    public const string SupplicantPath = "/etc/wpa_supplicant/palisade-wifi.conf";

    public static List<ValidationIssue> Validate(WifiRequest request)
    {
        var issues = new List<ValidationIssue>();
        var bytes = Encoding.UTF8.GetByteCount(request.Ssid);
        if (bytes is 0 or > 32 || request.Ssid.Any(char.IsControl))
            issues.Add(new("Wifi.Ssid", "Type the name of the Wi-Fi network. It can be up to 32 characters."));
        var pass = request.Passphrase;
        if (pass.Length > 0 && (pass.Length is < 8 or > 63 || pass.Any(ch => ch is < ' ' or > '~')))
            issues.Add(new("Wifi.Passphrase", "A Wi-Fi password has 8 to 63 characters. Leave it empty only for a network without a password."));
        return issues;
    }

    /// <summary>
    /// The settings file for the Wi-Fi client. The network name is written as hex digits and the password
    /// as the derived key, also hex digits, so nothing a person types can add a line or an option to it.
    /// </summary>
    public static string SupplicantConf(WifiRequest request)
    {
        if (Validate(request).Count > 0) throw new InvalidOperationException("Unsafe Wi-Fi settings.");
        var ssid = Encoding.UTF8.GetBytes(request.Ssid);
        var sb = new StringBuilder();
        sb.Append("# Generated by Palisade. Do not edit: changes are overwritten when the Wi-Fi is changed.\n");
        sb.Append("network={\n");
        sb.Append($"    ssid={Convert.ToHexStringLower(ssid)}\n");
        sb.Append("    scan_ssid=1\n");
        if (request.Passphrase.Length == 0) sb.Append("    key_mgmt=NONE\n");
        else
        {
            // The standard WPA2 key derivation: the same value the "wpa_passphrase" tool prints.
            var key = Rfc2898DeriveBytes.Pbkdf2(Encoding.ASCII.GetBytes(request.Passphrase), ssid, 4096, HashAlgorithmName.SHA1, 32);
            sb.Append($"    psk={Convert.ToHexStringLower(key)}\n");
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    public static string WifiStanza(string iface) =>
        $"# Generated by Palisade. Do not edit: changes are overwritten when the Wi-Fi is changed.\nallow-hotplug {Name(iface)}\niface {Name(iface)} inet dhcp\n    wpa-conf {SupplicantPath}\n";

    /// <summary>A wired internet port simply asks the provider's equipment for an address.</summary>
    public static string WiredStanza(string iface) =>
        $"# Generated by Palisade. Do not edit: changes are overwritten on the next save.\nallow-hotplug {Name(iface)}\niface {Name(iface)} inet dhcp\n";

    public static bool IsDefined(string interfacesFile, string iface) =>
        Regex.IsMatch(interfacesFile, $@"^[ \t]*iface[ \t]+{Regex.Escape(Name(iface))}[ \t]", RegexOptions.Multiline);

    /// <summary>
    /// Removes one port's settings from Debian's own interfaces file, leaving everything else as it was,
    /// so the same port is not described in two places once Palisade takes it over.
    /// </summary>
    public static string StripStanza(string interfacesFile, string iface)
    {
        var name = Regex.Escape(Name(iface));
        var kept = new List<string>();
        var skipping = false;
        foreach (var line in interfacesFile.Replace("\r\n", "\n").Split('\n'))
        {
            var text = line.Trim();
            if (Regex.IsMatch(text, $@"^(auto|allow-[a-z]+)\s+{name}$")) continue;
            if (Regex.IsMatch(text, $@"^iface\s+{name}\s"))
            {
                skipping = true;
                continue;
            }
            // A stanza's options are the lines after it, up to the next line that begins a new stanza.
            if (skipping && !Regex.IsMatch(text, @"^(iface|auto|allow-[a-z]+|source|source-directory|mapping)\s")) continue;
            skipping = false;
            kept.Add(line);
        }
        return string.Join('\n', kept);
    }

    private static string Name(string iface) =>
        iface.Length is > 0 and <= 15 && iface.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is '_' or '.' or '-')
            ? iface : throw new InvalidOperationException($"Unsafe port name: {iface}");
}
